.extern interrupt_dispatch

.global load_gdt
load_gdt:
    movl 4(%esp), %eax
    lgdt (%eax)
    ljmp $0x08, $1f
1:
    movw $0x10, %ax
    movw %ax, %ds
    movw %ax, %es
    movw %ax, %ss
    movw %ax, %fs
    movw %ax, %gs
    ret

.macro ISR_NOERR number
.global isr\number
isr\number:
    pushl $0
    pushl $\number
    jmp interrupt_common
.endm

.macro ISR_ERROR number
.global isr\number
isr\number:
    pushl $\number
    jmp interrupt_common
.endm

.macro IRQ_STUB number
.global irq\number
irq\number:
    pushl $0
    pushl $(32 + \number)
    jmp interrupt_common
.endm

