#include <stdint.h>
#include <stdio.h>

#include "secure_random.h"

int main(void)
{
    uint8_t bytes[32];
    int available = wpa2_secure_random_available();
    int generated = wpa2_secure_random_fill(0, bytes, sizeof(bytes));
    if (available == 0) {
        if (generated != 0) {
            fputs("WPA2 RNG generated bytes without advertised RDRAND\n",
                  stderr);
            return 1;
        }
        return 0;
    }
    if (generated == 0) {
        fputs("WPA2 RDRAND source failed after CPUID advertised support\n",
              stderr);
        return 1;
    }
    return 0;
}
